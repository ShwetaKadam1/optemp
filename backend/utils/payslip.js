// utils/payslip.js
import { jsPDF } from "jspdf";

export const generatePayslipPDFBuffer = async (employee, payroll) => {
  const doc = new jsPDF();

  // Header
  doc.setFontSize(18);
  doc.text("Payslip", 105, 18, { align: "center" });

  doc.setFontSize(11);
  doc.text(`Employee: ${employee.name}`, 20, 35);
  doc.text(`Employee ID: ${employee.employeeId || employee._id}`, 20, 42);
  doc.text(`Department: ${employee.department || "-"}`, 20, 49);
  doc.text(`Email: ${employee.email}`, 20, 56);

  // Payroll
  doc.text(`Month: ${payroll.month || "-"}`, 20, 72);
  doc.text(`Amount: ₹${Number(payroll.amount).toLocaleString("en-IN")}`, 20, 79);
  doc.text(`Status: ${payroll.status}`, 20, 86);
  doc.text(`Paid At: ${payroll.paidAt ? new Date(payroll.paidAt).toLocaleDateString() : "-"}`, 20, 93);

  // Footer
  doc.setFontSize(9);
  doc.text("Generated by Sutra HRMS", 105, 285, { align: "center" });

  const arrBuf = doc.output("arraybuffer");
  return arrBuf;
};
